#!/usr/bin/env python3
"""Optional real-Copilot E2E proof for the AgentForge bridge (ADR-0063).

CI deliberately takes the named skip path: Copilot model calls require credentials and can spend
credits. An operator explicitly opts in with AGENTFORGE_COPILOT_E2E=1; the harness then verifies a
bounded commit and a bridge-level out-of-boundary refusal in disposable repositories.
"""

import os
import shutil
import subprocess
import sys
import uuid
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
BRIDGE = ROOT / "scripts" / "agents" / "copilot-bridge"

TASK = {
    "contract_version": "1",
    "task_id": "P6-M010-T0001",
    "milestone_id": "P6-M010",
    "primary_role": "implementer",
    "goal": "Create docs/generated.md containing exactly `generated by Copilot`.",
    "non_goals": [],
    "dependency_task_ids": [],
    "allowed_paths": ["docs"],
    "forbidden_paths": ["docs/keep.md"],
    "capabilities": ["write_owned_paths"],
    "required_approvals": [],
    "required_gates": [],
    "expected_outputs": ["docs/generated.md"],
    "evidence_requirements": [],
}


def git(repo, *arguments):
    return subprocess.run(["git", *arguments], cwd=repo, check=True, capture_output=True, text=True)


def repository():
    directory = ROOT / f".agentforge-copilot-e2e-{uuid.uuid4().hex}"
    directory.mkdir()
    git(directory, "init", "-q", "-b", "main")
    git(directory, "config", "user.name", "Copilot E2E")
    git(directory, "config", "user.email", "e2e@example.invalid")
    git(directory, "config", "core.hooksPath", "")
    (directory / "docs").mkdir()
    (directory / "docs" / "keep.md").write_text("keep\n", encoding="utf-8")
    git(directory, "add", "-A")
    git(directory, "commit", "-q", "-m", "fixture")
    return directory


def run(copilot, repo, task):
    sys.path.insert(0, str(ROOT / "scripts" / "agents"))
    import bridge_kit

    return subprocess.run(
        [sys.executable, str(BRIDGE), "--copilot", copilot],
        cwd=repo,
        input=bridge_kit.encode_prompt(task),
        capture_output=True,
        timeout=600,
    )


def main():
    if os.environ.get("AGENTFORGE_COPILOT_E2E") != "1":
        print("copilot-e2e: SKIP: set AGENTFORGE_COPILOT_E2E=1 to permit real Copilot model requests")
        return 0
    copilot = shutil.which("copilot")
    if not copilot:
        print("copilot-e2e: SKIP: no GitHub Copilot CLI found")
        return 0
    commit_repo = refusal_repo = None
    try:
        commit_repo = repository()
        committed = run(copilot, commit_repo, TASK)
        if committed.returncode == 2:
            print("copilot-e2e: SKIP: Copilot credentials or MXC prerequisites unavailable")
            return 0
        if committed.returncode != 0:
            raise AssertionError(f"commit case exited {committed.returncode}: {committed.stderr.decode()[-500:]}")
        if (commit_repo / "docs" / "generated.md").read_text(encoding="utf-8").strip() != "generated by Copilot":
            raise AssertionError("commit case did not create the expected bounded file")
        if int(git(commit_repo, "rev-list", "--count", "HEAD").stdout) != 2:
            raise AssertionError("commit case did not create exactly one bridge commit")

        refusal_repo = repository()
        outside = dict(TASK, goal="Create OUTSIDE.md containing exactly `outside`.")
        refused = run(copilot, refusal_repo, outside)
        if refused.returncode != 4:
            raise AssertionError(f"refusal case exited {refused.returncode}: {refused.stderr.decode()[-500:]}")
        if int(git(refusal_repo, "rev-list", "--count", "HEAD").stdout) != 1:
            raise AssertionError("path violation must not commit")
        if not (refusal_repo / "OUTSIDE.md").exists():
            raise AssertionError("path violation must preserve its file for review")
    except (AssertionError, subprocess.SubprocessError, OSError) as error:
        print(f"copilot-e2e: FAIL: {error}", file=sys.stderr)
        return 1
    finally:
        for directory in (commit_repo, refusal_repo):
            if directory:
                shutil.rmtree(directory, ignore_errors=True)
    print("copilot-e2e: passed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
